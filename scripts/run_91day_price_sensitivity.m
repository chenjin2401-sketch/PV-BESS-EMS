%% run_91day_price_sensitivity.m
% Evaluate fixed-window and price-aware grid precharging against all
% 91 cleaned Shandong day-ahead economic-price profiles.
%
% Important interpretation:
% The same validated representative Sunny / Normal Load profile is used
% every day, and SOC is reset to 50% before each simulation. Therefore,
% this is a controlled price-sensitivity study, not a reconstruction of
% 91 days of historical site operation.

clear;
clc;
close all;

%% 1. Project paths and model

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);

dataDir = fullfile(projectDir, 'data');
modelDir = fullfile(projectDir, 'model');
resultsDir = fullfile(projectDir, 'results');

if ~exist(resultsDir, 'dir')
    mkdir(resultsDir);
end

modelName = 'PV_BESS_EMS_PRICE';
modelFile = fullfile(modelDir, [modelName '.slx']);

assert(isfile(modelFile), ...
    'Price-aware model not found: %s', modelFile);

addpath(modelDir);
load_system(modelFile);

set_param(modelName, 'StopTime', '86400');
set_param(modelName, 'FastRestart', 'off');

%% 2. Load the representative operating profiles and price data

loadData = load(fullfile(dataDir, 'load_profile.mat'));
pvData = load(fullfile(dataDir, 'pv_profile.mat'));
priceData = load(fullfile(dataDir, ...
    'day_ahead_price_data.mat'));

baseTime = loadData.load_profile.Time(:);
baseLoad = loadData.load_profile.Data(:);
basePV = pvData.pv_profile.Data(:);

assert(numel(baseLoad) == numel(basePV), ...
    'Load and PV profiles must have the same length.');

priceDateList = priceData.priceDateList(:);
numberOfDays = numel(priceDateList);

assert(numberOfDays == 91, ...
    'Expected 91 price days, but found %d.', numberOfDays);

assert(size(priceData.economicPriceClean_96xN, 1) == 96, ...
    'Each price day must contain 96 intervals.');

assert(size(priceData.economicPriceClean_96xN, 2) ...
    == numberOfDays, ...
    'Price matrix and date list have inconsistent day counts.');

imputedPriceDay = any( ...
    priceData.economicPriceImputed_96xN, 1)';

%% 3. Common engineering parameters

E_batt_kWh = 340;
P_batt_max_kW = 70;
P_grid_limit_kW = 100;

SOC_min = 0.20;
SOC_max = 0.90;
SOC_initial_value = 0.50;

precharge_enable_value = 1;

Strategy = [
    "Fixed 00:00-06:00 precharge"
    "Price-aware + deadline recovery"
];

PriceAwareEnable = [0; 1];
numberOfStrategies = numel(Strategy);

%% 4. Preallocate daily metrics

PeakGrid_kW = zeros(numberOfDays, numberOfStrategies);
GridImport_kWh = zeros(numberOfDays, numberOfStrategies);
GridExport_kWh = zeros(numberOfDays, numberOfStrategies);
NetGridEnergy_kWh = zeros(numberOfDays, numberOfStrategies);
GridExceedance_kWh = zeros(numberOfDays, numberOfStrategies);
RawEnergyCost_RMB = zeros(numberOfDays, numberOfStrategies);
BatteryThroughput_kWh = zeros(numberOfDays, numberOfStrategies);
MinimumSOC_pct = zeros(numberOfDays, numberOfStrategies);
MaximumSOC_pct = zeros(numberOfDays, numberOfStrategies);
FinalSOC_pct = zeros(numberOfDays, numberOfStrategies);
MaximumBatteryPower_kW = zeros(numberOfDays, numberOfStrategies);
MaximumPowerBalanceError_kW = zeros( ...
    numberOfDays, numberOfStrategies);
SOCIntegrationError_pct = zeros( ...
    numberOfDays, numberOfStrategies);

MeetsGridLimit = false(numberOfDays, numberOfStrategies);
SOCWithinLimits = false(numberOfDays, numberOfStrategies);
BatteryPowerWithinRating = false( ...
    numberOfDays, numberOfStrategies);
PowerBalanceValid = false(numberOfDays, numberOfStrategies);

DailyLowPriceThreshold_RMB_MWh = zeros(numberOfDays, 1);

%% 5. Run the 91-day controlled price sensitivity

fprintf('\n--- Running 91-day Price Sensitivity ---\n');
fprintf('Simulations required: %d\n\n', ...
    numberOfDays * numberOfStrategies);

for dayIndex = 1:numberOfDays

    priceVector96 = ...
        priceData.economicPriceClean_96xN(:, dayIndex);

    assert(all(isfinite(priceVector96)), ...
        'Cleaned price data contain invalid values on day %d.', ...
        dayIndex);

    priceTime_sec = (0:900:86400)';

    price_profile = timeseries( ...
        [priceVector96; priceVector96(end)], ...
        priceTime_sec);

    price_profile = setinterpmethod( ...
        price_profile, 'zoh');

    price_low_threshold_RMB_MWh = ...
        priceData.dailyLowPriceThreshold_RMB_MWh(dayIndex);

    DailyLowPriceThreshold_RMB_MWh(dayIndex) = ...
        price_low_threshold_RMB_MWh;

    for strategyIndex = 1:numberOfStrategies

        assignin('base', ...
            'load_profile', ...
            timeseries(baseLoad, baseTime));

        assignin('base', ...
            'pv_profile', ...
            timeseries(basePV, baseTime));

        assignin('base', 'E_batt', E_batt_kWh);
        assignin('base', 'E_batt_kWh', E_batt_kWh);

        assignin('base', ...
            'P_batt_max', P_batt_max_kW);

        assignin('base', ...
            'P_batt_max_kW', P_batt_max_kW);

        assignin('base', ...
            'P_grid_limit', P_grid_limit_kW);

        assignin('base', ...
            'P_grid_limit_kW', P_grid_limit_kW);

        assignin('base', ...
            'SOC_initial', SOC_initial_value);

        assignin('base', ...
            'precharge_enable', ...
            precharge_enable_value);

        assignin('base', ...
            'price_profile', price_profile);

        assignin('base', ...
            'price_low_threshold_RMB_MWh', ...
            price_low_threshold_RMB_MWh);

        assignin('base', ...
            'price_aware_enable', ...
            PriceAwareEnable(strategyIndex));

        % Prevent Simulation Data Inspector runs from filling the disk.
        Simulink.sdi.clear;

        simOut = sim(modelName, ...
            'StopTime', '86400', ...
            'ReturnWorkspaceOutputs', 'on');

        P_grid_ts = simOut.get('P_grid_ems_sim');
        P_grid_base_ts = simOut.get('P_grid_base_sim');
        P_batt_ts = simOut.get('P_batt_sim');
        SOC_ts = simOut.get('SOC_sim');

        dayTime = P_grid_ts.Time(:);
        P_grid = P_grid_ts.Data(:);
        P_grid_base = P_grid_base_ts.Data(:);
        P_batt = P_batt_ts.Data(:);
        SOC = SOC_ts.Data(:);

        assert(numel(dayTime) >= 2, ...
            'Simulation output contains too few samples.');

        assert(all(diff(dayTime) > 0), ...
            'Simulation time must be strictly increasing.');

        assert(abs(dayTime(1)) <= 1e-9 ...
            && abs(dayTime(end) - 86400) <= 1e-9, ...
            'Simulation output must cover 0 to 86400 seconds.');

        currentPrice = interp1( ...
            price_profile.Time(:), ...
            price_profile.Data(:), ...
            dayTime, ...
            'previous', ...
            'extrap');

        intervalHours = diff(dayTime) / 3600;

        assert(abs(sum(intervalHours) - 24) <= 1e-9, ...
            'The interval durations must sum to 24 hours.');

        gridInterval = P_grid(1:end-1);
        batteryInterval = P_batt(1:end-1);
        priceInterval = currentPrice(1:end-1);

        importPowerInterval = max(gridInterval, 0);
        exportPowerInterval = max(-gridInterval, 0);

        exceedancePowerInterval = max( ...
            gridInterval - P_grid_limit_kW, 0);

        PeakGrid_kW(dayIndex, strategyIndex) = ...
            max(P_grid);

        GridImport_kWh(dayIndex, strategyIndex) = sum( ...
            importPowerInterval .* intervalHours);

        GridExport_kWh(dayIndex, strategyIndex) = sum( ...
            exportPowerInterval .* intervalHours);

        NetGridEnergy_kWh(dayIndex, strategyIndex) = ...
            GridImport_kWh(dayIndex, strategyIndex) ...
            - GridExport_kWh(dayIndex, strategyIndex);

        GridExceedance_kWh(dayIndex, strategyIndex) = sum( ...
            exceedancePowerInterval .* intervalHours);

        RawEnergyCost_RMB(dayIndex, strategyIndex) = sum( ...
            importPowerInterval .* intervalHours ...
            .* priceInterval / 1000);

        BatteryThroughput_kWh(dayIndex, strategyIndex) = sum( ...
            abs(batteryInterval) .* intervalHours);

        % SOC(1) is the state after the first 15-minute update even
        % though Simulink timestamps that output at t = 0. Reconstruct
        % the physical state sequence at 0, 900, ..., 86400 seconds.
        SOC_state = [SOC_initial_value; SOC(1:end-1)];

        MinimumSOC_pct(dayIndex, strategyIndex) = ...
            100 * min(SOC_state);

        MaximumSOC_pct(dayIndex, strategyIndex) = ...
            100 * max(SOC_state);

        FinalSOC_pct(dayIndex, strategyIndex) = ...
            100 * SOC_state(end);

        chargedEnergyIntoCell_kWh = sum( ...
            max(-batteryInterval, 0) * 0.95 ...
            .* intervalHours);

        dischargedEnergyFromCell_kWh = sum( ...
            max(batteryInterval, 0) / 0.95 ...
            .* intervalHours);

        calculatedFinalSOC = SOC_initial_value ...
            + chargedEnergyIntoCell_kWh / E_batt_kWh ...
            - dischargedEnergyFromCell_kWh / E_batt_kWh;

        calculatedFinalSOC = min(max( ...
            calculatedFinalSOC, SOC_min), SOC_max);

        SOCIntegrationError_pct(dayIndex, strategyIndex) = ...
            100 * abs( ...
            calculatedFinalSOC - SOC_state(end));

        MaximumBatteryPower_kW(dayIndex, strategyIndex) = ...
            max(abs(P_batt));

        powerBalanceError = ...
            P_grid - (P_grid_base - P_batt);

        MaximumPowerBalanceError_kW(dayIndex, strategyIndex) = ...
            max(abs(powerBalanceError));

        MeetsGridLimit(dayIndex, strategyIndex) = ...
            PeakGrid_kW(dayIndex, strategyIndex) ...
            <= P_grid_limit_kW + 1e-6;

        SOCWithinLimits(dayIndex, strategyIndex) = ...
            min(SOC_state) >= SOC_min - 1e-9 ...
            && max(SOC_state) <= SOC_max + 1e-9;

        BatteryPowerWithinRating(dayIndex, strategyIndex) = ...
            max(abs(P_batt)) ...
            <= P_batt_max_kW + 1e-6;

        PowerBalanceValid(dayIndex, strategyIndex) = ...
            MaximumPowerBalanceError_kW( ...
            dayIndex, strategyIndex) <= 1e-6;
    end

    if mod(dayIndex, 10) == 0 ...
            || dayIndex == numberOfDays

        fprintf('Completed price day %d of %d\n', ...
            dayIndex, numberOfDays);
    end
end

%% 6. Daily comparison and validity gates

FixedCost_RMB = RawEnergyCost_RMB(:, 1);
PriceAwareCost_RMB = RawEnergyCost_RMB(:, 2);

RawSaving_RMB = ...
    FixedCost_RMB - PriceAwareCost_RMB;

RawSaving_pct = NaN(numberOfDays, 1);

nonzeroFixedCost = abs(FixedCost_RMB) > 1e-9;

RawSaving_pct(nonzeroFixedCost) = ...
    100 * RawSaving_RMB(nonzeroFixedCost) ...
    ./ FixedCost_RMB(nonzeroFixedCost);

FixedGridImport_kWh = GridImport_kWh(:, 1);
PriceAwareGridImport_kWh = GridImport_kWh(:, 2);

GridImportReduction_kWh = ...
    FixedGridImport_kWh ...
    - PriceAwareGridImport_kWh;

FixedFinalSOC_pct = FinalSOC_pct(:, 1);
PriceAwareFinalSOC_pct = FinalSOC_pct(:, 2);

TerminalSOCDifference_pct = ...
    PriceAwareFinalSOC_pct ...
    - FixedFinalSOC_pct;

TerminalSOCComparable = ...
    abs(TerminalSOCDifference_pct) <= 0.5;

FixedReliabilityValid = ...
    MeetsGridLimit(:, 1) ...
    & SOCWithinLimits(:, 1) ...
    & BatteryPowerWithinRating(:, 1) ...
    & PowerBalanceValid(:, 1) ...
    & (SOCIntegrationError_pct(:, 1) <= 1e-6);

PriceAwareReliabilityValid = ...
    MeetsGridLimit(:, 2) ...
    & SOCWithinLimits(:, 2) ...
    & BatteryPowerWithinRating(:, 2) ...
    & PowerBalanceValid(:, 2) ...
    & (SOCIntegrationError_pct(:, 2) <= 1e-6);

ValidDirectComparison = ...
    FixedReliabilityValid ...
    & PriceAwareReliabilityValid ...
    & TerminalSOCComparable;

%% 7. Save the 91-row daily result table

DailyResults = table( ...
    priceDateList, ...
    imputedPriceDay, ...
    DailyLowPriceThreshold_RMB_MWh, ...
    FixedCost_RMB, ...
    PriceAwareCost_RMB, ...
    RawSaving_RMB, ...
    RawSaving_pct, ...
    FixedGridImport_kWh, ...
    PriceAwareGridImport_kWh, ...
    GridImportReduction_kWh, ...
    GridExport_kWh(:, 1), ...
    GridExport_kWh(:, 2), ...
    NetGridEnergy_kWh(:, 1), ...
    NetGridEnergy_kWh(:, 2), ...
    PeakGrid_kW(:, 1), ...
    PeakGrid_kW(:, 2), ...
    GridExceedance_kWh(:, 1), ...
    GridExceedance_kWh(:, 2), ...
    BatteryThroughput_kWh(:, 1), ...
    BatteryThroughput_kWh(:, 2), ...
    FixedFinalSOC_pct, ...
    PriceAwareFinalSOC_pct, ...
    TerminalSOCDifference_pct, ...
    SOCIntegrationError_pct(:, 1), ...
    SOCIntegrationError_pct(:, 2), ...
    FixedReliabilityValid, ...
    PriceAwareReliabilityValid, ...
    TerminalSOCComparable, ...
    ValidDirectComparison, ...
    'VariableNames', { ...
    'PriceDate', ...
    'ImputedPriceDay', ...
    'LowPriceThreshold_RMB_MWh', ...
    'FixedCost_RMB', ...
    'PriceAwareCost_RMB', ...
    'RawSaving_RMB', ...
    'RawSaving_pct', ...
    'FixedGridImport_kWh', ...
    'PriceAwareGridImport_kWh', ...
    'GridImportReduction_kWh', ...
    'FixedGridExport_kWh', ...
    'PriceAwareGridExport_kWh', ...
    'FixedNetGridEnergy_kWh', ...
    'PriceAwareNetGridEnergy_kWh', ...
    'FixedPeakGrid_kW', ...
    'PriceAwarePeakGrid_kW', ...
    'FixedGridExceedance_kWh', ...
    'PriceAwareGridExceedance_kWh', ...
    'FixedBatteryThroughput_kWh', ...
    'PriceAwareBatteryThroughput_kWh', ...
    'FixedFinalSOC_pct', ...
    'PriceAwareFinalSOC_pct', ...
    'TerminalSOCDifference_pct', ...
    'FixedSOCIntegrationError_pct', ...
    'PriceAwareSOCIntegrationError_pct', ...
    'FixedReliabilityValid', ...
    'PriceAwareReliabilityValid', ...
    'TerminalSOCComparable', ...
    'ValidDirectComparison'});

%% 8. Aggregate only defensible comparisons

% The fixed strategy must have identical physical dispatch results on
% every price day. Its cost changes with price, but price must not leak
% into its grid power, energy, SOC or battery dispatch.
fixedPhysicalInvariant = ...
    max(abs(PeakGrid_kW(:, 1) ...
    - PeakGrid_kW(1, 1))) <= 1e-6 ...
    && max(abs(GridImport_kWh(:, 1) ...
    - GridImport_kWh(1, 1))) <= 1e-6 ...
    && max(abs(GridExport_kWh(:, 1) ...
    - GridExport_kWh(1, 1))) <= 1e-6 ...
    && max(abs(BatteryThroughput_kWh(:, 1) ...
    - BatteryThroughput_kWh(1, 1))) <= 1e-6 ...
    && max(abs(MinimumSOC_pct(:, 1) ...
    - MinimumSOC_pct(1, 1))) <= 1e-6 ...
    && max(abs(MaximumSOC_pct(:, 1) ...
    - MaximumSOC_pct(1, 1))) <= 1e-6 ...
    && max(abs(FinalSOC_pct(:, 1) ...
    - FinalSOC_pct(1, 1))) <= 1e-6;

Scope = [
    "Observed price days only"
    "Including imputed price day"
];

scopeMaskMatrix = [ ...
    ~imputedPriceDay, ...
    true(numberOfDays, 1) ...
];

numberOfScopes = numel(Scope);

PriceDays = zeros(numberOfScopes, 1);
ImputedPriceDays = zeros(numberOfScopes, 1);
FixedReliabilityValidDays = zeros(numberOfScopes, 1);
PriceAwareReliabilityValidDays = zeros(numberOfScopes, 1);
ValidComparableDays = zeros(numberOfScopes, 1);
TotalComparableSaving_RMB = NaN(numberOfScopes, 1);
ComparableCostReduction_pct = NaN(numberOfScopes, 1);
MeanComparableSaving_RMB = NaN(numberOfScopes, 1);
MedianComparableSaving_RMB = NaN(numberOfScopes, 1);
P05ComparableSaving_RMB = NaN(numberOfScopes, 1);
P25ComparableSaving_RMB = NaN(numberOfScopes, 1);
P75ComparableSaving_RMB = NaN(numberOfScopes, 1);
P95ComparableSaving_RMB = NaN(numberOfScopes, 1);
MinimumComparableSaving_RMB = NaN(numberOfScopes, 1);
MaximumComparableSaving_RMB = NaN(numberOfScopes, 1);
PositiveSavingDays = zeros(numberOfScopes, 1);
NegativeSavingDays = zeros(numberOfScopes, 1);
PositiveSavingShare_pct = NaN(numberOfScopes, 1);

for scopeIndex = 1:numberOfScopes

    currentScopeMask = scopeMaskMatrix(:, scopeIndex);

    currentValidMask = ...
        currentScopeMask & ValidDirectComparison;

    PriceDays(scopeIndex) = sum(currentScopeMask);

    ImputedPriceDays(scopeIndex) = sum( ...
        currentScopeMask & imputedPriceDay);

    FixedReliabilityValidDays(scopeIndex) = sum( ...
        currentScopeMask & FixedReliabilityValid);

    PriceAwareReliabilityValidDays(scopeIndex) = sum( ...
        currentScopeMask & PriceAwareReliabilityValid);

    ValidComparableDays(scopeIndex) = sum( ...
        currentValidMask);

    currentSavings = RawSaving_RMB(currentValidMask);
    currentFixedCost = FixedCost_RMB(currentValidMask);

    if ~isempty(currentSavings)

        TotalComparableSaving_RMB(scopeIndex) = ...
            sum(currentSavings);

        if abs(sum(currentFixedCost)) > 1e-9
            ComparableCostReduction_pct(scopeIndex) = ...
                100 * sum(currentSavings) ...
                / sum(currentFixedCost);
        end

        MeanComparableSaving_RMB(scopeIndex) = ...
            mean(currentSavings);

        MedianComparableSaving_RMB(scopeIndex) = ...
            median(currentSavings);

        savingPercentiles = prctile( ...
            currentSavings, [5 25 75 95]);

        P05ComparableSaving_RMB(scopeIndex) = ...
            savingPercentiles(1);

        P25ComparableSaving_RMB(scopeIndex) = ...
            savingPercentiles(2);

        P75ComparableSaving_RMB(scopeIndex) = ...
            savingPercentiles(3);

        P95ComparableSaving_RMB(scopeIndex) = ...
            savingPercentiles(4);

        MinimumComparableSaving_RMB(scopeIndex) = ...
            min(currentSavings);

        MaximumComparableSaving_RMB(scopeIndex) = ...
            max(currentSavings);

        PositiveSavingDays(scopeIndex) = ...
            sum(currentSavings > 1e-9);

        NegativeSavingDays(scopeIndex) = ...
            sum(currentSavings < -1e-9);

        PositiveSavingShare_pct(scopeIndex) = ...
            100 * mean(currentSavings > 1e-9);
    end
end

Summary = table( ...
    Scope, ...
    PriceDays, ...
    ImputedPriceDays, ...
    FixedReliabilityValidDays, ...
    PriceAwareReliabilityValidDays, ...
    ValidComparableDays, ...
    TotalComparableSaving_RMB, ...
    ComparableCostReduction_pct, ...
    MeanComparableSaving_RMB, ...
    MedianComparableSaving_RMB, ...
    P05ComparableSaving_RMB, ...
    P25ComparableSaving_RMB, ...
    P75ComparableSaving_RMB, ...
    P95ComparableSaving_RMB, ...
    MinimumComparableSaving_RMB, ...
    MaximumComparableSaving_RMB, ...
    PositiveSavingDays, ...
    NegativeSavingDays, ...
    PositiveSavingShare_pct);

% Use only the 90 non-imputed price days for the headline plot and claim.
mainAnalysisMask = ...
    ~imputedPriceDay & ValidDirectComparison;

comparableSavings = RawSaving_RMB(mainAnalysisMask);
numberComparableDays = sum(mainAnalysisMask);

%% 9. Display the engineering verdict

fprintf('\n--- 91-day Price Sensitivity Summary ---\n');
disp(Summary);

fprintf('\n--- Interpretation Boundary ---\n');
fprintf(['This is a controlled price-sensitivity study using one ', ...
    'repeated representative load/PV day.\n']);
fprintf(['It is not a historical reconstruction of site operation ', ...
    'and must not be annualized as a guaranteed return.\n']);
fprintf(['Headline statistics exclude the one fully imputed ', ...
    'price day; the second summary row is sensitivity only.\n']);
fprintf(['Energy cost includes grid imports only and assumes ', ...
    'zero compensation for grid exports.\n']);
fprintf('Fixed-strategy physical invariance across price days: %d\n', ...
    fixedPhysicalInvariant);

numberObservedDays = sum(~imputedPriceDay);

if numberComparableDays == numberObservedDays ...
        && fixedPhysicalInvariant

    fprintf(['All %d observed price days passed reliability and ', ...
        'comparability gates.\n'], ...
        numberObservedDays);

else

    fprintf(['Only %d of %d observed price days passed all ', ...
        'direct-comparison ', ...
        'gates.\n'], ...
        numberComparableDays, numberObservedDays);

    fprintf(['Do not summarize invalid days as verified ', ...
        'economic savings.\n']);
end

