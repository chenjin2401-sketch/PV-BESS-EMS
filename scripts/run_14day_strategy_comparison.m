%% run_14day_strategy_comparison.m
% Compare forecast-based precharging with no precharging
% over two repeated operating weeks.

clear;
clc;
close all;

%% 1. Project paths

scriptDir  = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);

dataDir    = fullfile(projectDir, 'data');
modelDir   = fullfile(projectDir, 'model');
resultsDir = fullfile(projectDir, 'results');

if ~exist(resultsDir, 'dir')
    mkdir(resultsDir);
end

modelName = 'PV_BESS_EMS';
modelFile = fullfile(modelDir, [modelName '.slx']);

addpath(modelDir);
load_system(modelFile);

set_param(modelName, 'StopTime', '86400');
set_param(modelName, 'FastRestart', 'off');

%% 2. Load validated daily profiles

loadData = load(fullfile(dataDir, 'load_profile.mat'));
pvData   = load(fullfile(dataDir, 'pv_profile.mat'));

baseTime = loadData.load_profile.Time(:);
baseLoad = loadData.load_profile.Data(:);
basePV   = pvData.pv_profile.Data(:);

assert(numel(baseLoad) == numel(basePV), ...
    'Load and PV profiles must have the same length.');

%% 3. BESS parameters

E_batt_kWh = 340;
P_batt_max_kW = 70;
P_grid_limit_kW = 100;

SOC_min = 0.20;
SOC_max = 0.90;

projectInitialSOC = 0.50;

%% 4. Define one-week operating schedule

weeklyScenario = [
    "Sunny / Normal Load"
    "Sunny / Normal Load"
    "Cloudy / Normal Load"
    "Cloudy / High Load"
    "Cloudy / High Load"
    "Sunny / High Load"
    "Sunny / Normal Load"
];

weeklyPVScale = [
    1.00
    1.00
    0.55
    0.55
    0.55
    1.00
    1.00
];

weeklyLoadScale = [
    1.00
    1.00
    1.00
    1.15
    1.15
    1.15
    1.00
];

weeklyForecastPrecharge = [
    0
    0
    1
    1
    1
    1
    0
];

%% 5. Repeat the schedule for two weeks

numberOfWeeks = 2;
numberOfDays = 7 * numberOfWeeks;

DayNumber = (1:numberOfDays)';

Scenario = repmat( ...
    weeklyScenario, numberOfWeeks, 1);

PVScale = repmat( ...
    weeklyPVScale, numberOfWeeks, 1);

LoadScale = repmat( ...
    weeklyLoadScale, numberOfWeeks, 1);

forecastPrechargeFlags = repmat( ...
    weeklyForecastPrecharge, numberOfWeeks, 1);

%% 6. Define the two strategies

StrategyName = [
    "Forecast-based precharge"
    "No precharge"
];

numberOfStrategies = numel(StrategyName);

strategyPrechargeFlags = [
    forecastPrechargeFlags, ...
    zeros(numberOfDays, 1)
];

%% 7. Preallocate result matrices

InitialSOC_pct = zeros( ...
    numberOfDays, numberOfStrategies);

FinalSOC_pct = zeros( ...
    numberOfDays, numberOfStrategies);

MinimumSOC_pct = zeros( ...
    numberOfDays, numberOfStrategies);

MaximumSOC_pct = zeros( ...
    numberOfDays, numberOfStrategies);

PeakGrid_kW = zeros( ...
    numberOfDays, numberOfStrategies);

GridExceedance_kWh = zeros( ...
    numberOfDays, numberOfStrategies);

MaximumBatteryPower_kW = zeros( ...
    numberOfDays, numberOfStrategies);

MaximumPowerBalanceError_kW = zeros( ...
    numberOfDays, numberOfStrategies);

HandoverError_pct = zeros( ...
    numberOfDays, numberOfStrategies);

MeetsGridLimit = false( ...
    numberOfDays, numberOfStrategies);

SOCWithinLimits = false( ...
    numberOfDays, numberOfStrategies);

BatteryPowerWithinRating = false( ...
    numberOfDays, numberOfStrategies);

continuousTime = cell( ...
    numberOfStrategies, 1);

continuousSOC = cell( ...
    numberOfStrategies, 1);

%% 8. Arrays for the long-form result table

numberOfRows = ...
    numberOfDays * numberOfStrategies;

StrategyColumn = strings(numberOfRows, 1);
DayColumn = zeros(numberOfRows, 1);
ScenarioColumn = strings(numberOfRows, 1);
PrechargeColumn = zeros(numberOfRows, 1);

InitialSOCColumn = zeros(numberOfRows, 1);
FinalSOCColumn = zeros(numberOfRows, 1);
MinimumSOCColumn = zeros(numberOfRows, 1);
MaximumSOCColumn = zeros(numberOfRows, 1);

PeakGridColumn = zeros(numberOfRows, 1);
ExceedanceColumn = zeros(numberOfRows, 1);

HandoverErrorColumn = zeros(numberOfRows, 1);
PowerBalanceErrorColumn = zeros(numberOfRows, 1);

MeetsGridColumn = false(numberOfRows, 1);
SOCWithinLimitsColumn = false(numberOfRows, 1);
BatteryPowerWithinRatingColumn = false(numberOfRows, 1);

%% 9. Run both strategies

rowIndex = 0;

for strategyIndex = 1:numberOfStrategies

    fprintf('\n========================================\n');
    fprintf('Running strategy: %s\n', ...
        StrategyName(strategyIndex));
    fprintf('========================================\n');

    currentStrategyTime = [];
    currentStrategySOC = [];

    for dayIndex = 1:numberOfDays

        fprintf('\nDay %d of %d: %s\n', ...
            dayIndex, ...
            numberOfDays, ...
            Scenario(dayIndex));

        %% 9.1 SOC handover

        if dayIndex == 1

            currentInitialSOC = ...
                projectInitialSOC;

        else

            currentInitialSOC = ...
                FinalSOC_pct( ...
                dayIndex - 1, strategyIndex) / 100;

        end

        InitialSOC_pct( ...
            dayIndex, strategyIndex) = ...
            100 * currentInitialSOC;

        if dayIndex == 1

            HandoverError_pct( ...
                dayIndex, strategyIndex) = 0;

        else

            HandoverError_pct( ...
                dayIndex, strategyIndex) = abs( ...
                InitialSOC_pct( ...
                dayIndex, strategyIndex) - ...
                FinalSOC_pct( ...
                dayIndex - 1, strategyIndex));

        end

        %% 9.2 Current-day profiles

        currentLoad = ...
            baseLoad * LoadScale(dayIndex);

        currentPV = ...
            basePV * PVScale(dayIndex);

        load_profile_case = timeseries( ...
            currentLoad, baseTime);

        pv_profile_case = timeseries( ...
            currentPV, baseTime);

        %% 9.3 Assign model variables

        assignin('base', ...
            'load_profile', load_profile_case);

        assignin('base', ...
            'pv_profile', pv_profile_case);

        assignin('base', ...
            'E_batt', E_batt_kWh);

        assignin('base', ...
            'E_batt_kWh', E_batt_kWh);

        assignin('base', ...
            'P_batt_max', P_batt_max_kW);

        assignin('base', ...
            'P_batt_max_kW', P_batt_max_kW);

        assignin('base', ...
            'P_grid_limit', P_grid_limit_kW);

        assignin('base', ...
            'P_grid_limit_kW', P_grid_limit_kW);

        assignin('base', ...
            'SOC_initial', currentInitialSOC);

        currentPrechargeFlag = ...
            strategyPrechargeFlags( ...
            dayIndex, strategyIndex);

        assignin('base', ...
            'precharge_enable', ...
            currentPrechargeFlag);

        Simulink.sdi.clear;

        %% 9.4 Run one day

        simOut = sim(modelName, ...
            'StopTime', '86400', ...
            'ReturnWorkspaceOutputs', 'on');

        %% 9.5 Extract outputs

        P_grid_ts = ...
            simOut.get('P_grid_ems_sim');

        P_batt_ts = ...
            simOut.get('P_batt_sim');

        SOC_ts = ...
            simOut.get('SOC_sim');

        dayTime = P_grid_ts.Time(:);
        P_grid = P_grid_ts.Data(:);
        P_batt = P_batt_ts.Data(:);
        SOC = SOC_ts.Data(:);

        %% 9.6 Daily metrics

        FinalSOC_pct( ...
            dayIndex, strategyIndex) = ...
            100 * SOC(end);

        MinimumSOC_pct( ...
            dayIndex, strategyIndex) = ...
            100 * min(SOC);

        MaximumSOC_pct( ...
            dayIndex, strategyIndex) = ...
            100 * max(SOC);

        PeakGrid_kW( ...
            dayIndex, strategyIndex) = ...
            max(P_grid);

        excessPower = max( ...
            P_grid - P_grid_limit_kW, 0);

        GridExceedance_kWh( ...
            dayIndex, strategyIndex) = ...
            trapz(dayTime, excessPower) / 3600;

        MaximumBatteryPower_kW( ...
            dayIndex, strategyIndex) = ...
            max(abs(P_batt));

        MeetsGridLimit( ...
            dayIndex, strategyIndex) = ...
            PeakGrid_kW( ...
            dayIndex, strategyIndex) <= ...
            P_grid_limit_kW + 0.01 && ...
            GridExceedance_kWh( ...
            dayIndex, strategyIndex) <= 0.01;

        SOCWithinLimits( ...
            dayIndex, strategyIndex) = ...
            min(SOC) >= SOC_min - 1e-6 && ...
            max(SOC) <= SOC_max + 1e-6;

        BatteryPowerWithinRating( ...
            dayIndex, strategyIndex) = ...
            max(abs(P_batt)) <= ...
            P_batt_max_kW + 1e-6;

        %% 9.7 Power-balance verification

        P_net = currentLoad - currentPV;

        commonLength = min([ ...
            numel(P_net), ...
            numel(P_grid), ...
            numel(P_batt)]);

        balanceError = ...
            P_grid(1:commonLength) - ...
            (P_net(1:commonLength) - ...
             P_batt(1:commonLength));

        MaximumPowerBalanceError_kW( ...
            dayIndex, strategyIndex) = ...
            max(abs(balanceError));

        %% 9.8 Continuous SOC curve

        if dayIndex < numberOfDays

            keepSample = dayTime < 86400;

        else

            keepSample = dayTime <= 86400;

        end

        globalTime = ...
            (dayIndex - 1) * 86400 + ...
            dayTime(keepSample);

        currentStrategyTime = [
            currentStrategyTime
            globalTime
        ];

        currentStrategySOC = [
            currentStrategySOC
            100 * SOC(keepSample)
        ];

        %% 9.9 Add result-table row

        rowIndex = rowIndex + 1;

        StrategyColumn(rowIndex) = ...
            StrategyName(strategyIndex);

        DayColumn(rowIndex) = dayIndex;

        ScenarioColumn(rowIndex) = ...
            Scenario(dayIndex);

        PrechargeColumn(rowIndex) = ...
            currentPrechargeFlag;

        InitialSOCColumn(rowIndex) = ...
            InitialSOC_pct( ...
            dayIndex, strategyIndex);

        FinalSOCColumn(rowIndex) = ...
            FinalSOC_pct( ...
            dayIndex, strategyIndex);

        MinimumSOCColumn(rowIndex) = ...
            MinimumSOC_pct( ...
            dayIndex, strategyIndex);

        MaximumSOCColumn(rowIndex) = ...
            MaximumSOC_pct( ...
            dayIndex, strategyIndex);

        PeakGridColumn(rowIndex) = ...
            PeakGrid_kW( ...
            dayIndex, strategyIndex);

        ExceedanceColumn(rowIndex) = ...
            GridExceedance_kWh( ...
            dayIndex, strategyIndex);

        HandoverErrorColumn(rowIndex) = ...
            HandoverError_pct( ...
            dayIndex, strategyIndex);

        PowerBalanceErrorColumn(rowIndex) = ...
            MaximumPowerBalanceError_kW( ...
            dayIndex, strategyIndex);

        MeetsGridColumn(rowIndex) = ...
            MeetsGridLimit( ...
            dayIndex, strategyIndex);

        SOCWithinLimitsColumn(rowIndex) = ...
            SOCWithinLimits( ...
            dayIndex, strategyIndex);

        BatteryPowerWithinRatingColumn(rowIndex) = ...
            BatteryPowerWithinRating( ...
            dayIndex, strategyIndex);

    end

    continuousTime{strategyIndex} = ...
        currentStrategyTime;

    continuousSOC{strategyIndex} = ...
        currentStrategySOC;

end

%% 10. Create daily result table

strategyDailyResults = table( ...
    StrategyColumn, ...
    DayColumn, ...
    ScenarioColumn, ...
    PrechargeColumn, ...
    InitialSOCColumn, ...
    FinalSOCColumn, ...
    MinimumSOCColumn, ...
    MaximumSOCColumn, ...
    PeakGridColumn, ...
    ExceedanceColumn, ...
    HandoverErrorColumn, ...
    PowerBalanceErrorColumn, ...
    MeetsGridColumn, ...
    SOCWithinLimitsColumn, ...
    BatteryPowerWithinRatingColumn, ...
    'VariableNames', { ...
    'Strategy', ...
    'DayNumber', ...
    'Scenario', ...
    'PrechargeEnable', ...
    'InitialSOC_pct', ...
    'FinalSOC_pct', ...
    'MinimumSOC_pct', ...
    'MaximumSOC_pct', ...
    'PeakGrid_kW', ...
    'GridExceedance_kWh', ...
    'HandoverError_pct', ...
    'MaximumPowerBalanceError_kW', ...
    'MeetsGridLimit', ...
    'SOCWithinLimits', ...
    'BatteryPowerWithinRating'});

%% 11. Strategy-level summary

CompliantDays = zeros( ...
    numberOfStrategies, 1);

ViolatingDays = zeros( ...
    numberOfStrategies, 1);

TotalGridExceedance_kWh = zeros( ...
    numberOfStrategies, 1);

MaximumGridPower_kW = zeros( ...
    numberOfStrategies, 1);

OverallMinimumSOC_pct = zeros( ...
    numberOfStrategies, 1);

Week1FinalSOC_pct = zeros( ...
    numberOfStrategies, 1);

Week2FinalSOC_pct = zeros( ...
    numberOfStrategies, 1);

MaximumHandoverError_pct = zeros( ...
    numberOfStrategies, 1);

MaximumBalanceError_kW = zeros( ...
    numberOfStrategies, 1);

for strategyIndex = 1:numberOfStrategies

    CompliantDays(strategyIndex) = ...
        sum(MeetsGridLimit(:, strategyIndex));

    ViolatingDays(strategyIndex) = ...
        numberOfDays - ...
        CompliantDays(strategyIndex);

    TotalGridExceedance_kWh(strategyIndex) = ...
        sum(GridExceedance_kWh(:, strategyIndex));

    MaximumGridPower_kW(strategyIndex) = ...
        max(PeakGrid_kW(:, strategyIndex));

    OverallMinimumSOC_pct(strategyIndex) = ...
        min(MinimumSOC_pct(:, strategyIndex));

    Week1FinalSOC_pct(strategyIndex) = ...
        FinalSOC_pct(7, strategyIndex);

    Week2FinalSOC_pct(strategyIndex) = ...
        FinalSOC_pct(14, strategyIndex);

    MaximumHandoverError_pct(strategyIndex) = ...
        max(HandoverError_pct(:, strategyIndex));

    MaximumBalanceError_kW(strategyIndex) = ...
        max(MaximumPowerBalanceError_kW( ...
        :, strategyIndex));

end

strategySummary = table( ...
    StrategyName, ...
    CompliantDays, ...
    ViolatingDays, ...
    TotalGridExceedance_kWh, ...
    MaximumGridPower_kW, ...
    OverallMinimumSOC_pct, ...
    Week1FinalSOC_pct, ...
    Week2FinalSOC_pct, ...
    MaximumHandoverError_pct, ...
    MaximumBalanceError_kW);

fprintf('\n--- Fourteen-day Strategy Summary ---\n');

disp(strategySummary);

fprintf('\n--- Grid-limit Violation Days ---\n');

disp(strategyDailyResults( ...
    ~strategyDailyResults.MeetsGridLimit, { ...
    'Strategy', ...
    'DayNumber', ...
    'Scenario', ...
    'PrechargeEnable', ...
    'InitialSOC_pct', ...
    'FinalSOC_pct', ...
    'PeakGrid_kW', ...
    'GridExceedance_kWh'}));

%% 12. Save results

dailyCSV = fullfile( ...
    resultsDir, ...
    'fourteen_day_strategy_daily_results.csv');

summaryCSV = fullfile( ...
    resultsDir, ...
    'fourteen_day_strategy_summary.csv');

matFile = fullfile( ...
    resultsDir, ...
    'fourteen_day_strategy_comparison.mat');

writetable(strategyDailyResults, dailyCSV);
writetable(strategySummary, summaryCSV);

save(matFile, ...
    'strategyDailyResults', ...
    'strategySummary', ...
    'continuousTime', ...
    'continuousSOC', ...
    'PeakGrid_kW', ...
    'FinalSOC_pct', ...
    'StrategyName');

%% 13. Plot strategy comparison

figure( ...
    'Color', 'w', ...
    'Name', 'Fourteen-day Strategy Comparison');

tiledlayout(3, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

% Continuous SOC
nexttile;

for strategyIndex = 1:numberOfStrategies

    plot( ...
        continuousTime{strategyIndex} / 86400, ...
        continuousSOC{strategyIndex}, ...
        'LineWidth', 1.5);

    hold on;

end

yline(20, 'r--', ...
    '20% SOC limit');

yline(25, 'k--', ...
    '25% design target');

yline(90, 'r--', ...
    '90% SOC limit');

xline(7, 'k:', ...
    'Week 2');

grid on;
box on;

xlim([0 14]);
xticks(0:14);

ylabel('SOC (%)');
title('Continuous SOC');

legend(StrategyName, ...
    'Location', 'best');

% Daily peak grid power
nexttile;

for strategyIndex = 1:numberOfStrategies

    plot( ...
        DayNumber, ...
        PeakGrid_kW(:, strategyIndex), ...
        'o-', ...
        'LineWidth', 1.5);

    hold on;

end

yline(100, 'r--', ...
    '100 kW grid limit');

xline(7.5, 'k:', ...
    'Week boundary');

grid on;
box on;

xticks(DayNumber);
ylabel('Peak grid power (kW)');
title('Daily Peak Grid Power');

legend(StrategyName, ...
    'Location', 'best');

% Daily final SOC
nexttile;

for strategyIndex = 1:numberOfStrategies

    plot( ...
        DayNumber, ...
        FinalSOC_pct(:, strategyIndex), ...
        's-', ...
        'LineWidth', 1.5);

    hold on;

end

yline(20, 'r--', ...
    '20% SOC limit');

yline(25, 'k--', ...
    '25% design target');

xline(7.5, 'k:', ...
    'Week boundary');

grid on;
box on;

xticks(DayNumber);
xlabel('Day');
ylabel('Final SOC (%)');
title('Daily Final SOC');

legend(StrategyName, ...
    'Location', 'best');

sgtitle( ...
    'Fourteen-day Precharge Strategy Comparison');

exportgraphics(gcf, ...
    fullfile(resultsDir, ...
    'fourteen_day_strategy_comparison.png'), ...
    'Resolution', 300);

fprintf('\nResults saved to:\n%s\n', resultsDir);