%% run_price_aware_single_day_comparison.m
% Compare the validated fixed-window precharge rule with the new
% Price-aware + deadline recovery rule under identical one-day operating conditions.

clear;
clc;
close all;

%% 1. Project paths and model

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);

dataDir = fullfile(projectDir, 'data');
modelDir = fullfile(projectDir, 'model');
resultsDir = fullfile(projectDir, 'results');

if ~exist(resultsDir, 'dir')
    mkdir(resultsDir);
end

modelName = 'PV_BESS_EMS_PRICE';
modelFile = fullfile(modelDir, [modelName '.slx']);

assert(isfile(modelFile), ...
    'Price-aware model not found: %s', modelFile);

addpath(modelDir);
load_system(modelFile);

set_param(modelName, 'StopTime', '86400');
set_param(modelName, 'FastRestart', 'off');

%% 2. Load validated profiles and cleaned price data

loadData = load(fullfile(dataDir, 'load_profile.mat'));
pvData = load(fullfile(dataDir, 'pv_profile.mat'));
priceData = load(fullfile(dataDir, ...
    'day_ahead_price_data.mat'));

baseTime = loadData.load_profile.Time(:);
baseLoad = loadData.load_profile.Data(:);
basePV = pvData.pv_profile.Data(:);

assert(numel(baseLoad) == numel(basePV), ...
    'Load and PV profiles must have the same length.');

%% 3. Select the price day and construct a ZOH signal

priceDayIndex = 1;

assert(priceDayIndex >= 1 && ...
    priceDayIndex <= numel(priceData.priceDateList), ...
    'priceDayIndex is outside the available dataset.');

priceVector96 = ...
    priceData.economicPriceClean_96xN(:, priceDayIndex);

assert(all(isfinite(priceVector96)), ...
    'Selected economic-price day contains invalid values.');

priceTime_sec = (0:900:86400)';

price_profile = timeseries( ...
    [priceVector96; priceVector96(end)], ...
    priceTime_sec);

price_profile = setinterpmethod(price_profile, 'zoh');

price_low_threshold_RMB_MWh = ...
    priceData.dailyLowPriceThreshold_RMB_MWh( ...
    priceDayIndex);

%% 4. Common engineering parameters

E_batt_kWh = 340;
P_batt_max_kW = 70;
P_grid_limit_kW = 100;

SOC_min = 0.20;
SOC_max = 0.90;
SOC_initial_value = 0.50;

% The same precharge need is supplied to both strategies.
precharge_enable_value = 1;

%% 5. Define the A/B strategies

Strategy = [
    "Fixed 00:00-06:00 precharge"
    "Price-aware precharge"
];

PriceAwareEnable = [
    0
    1
];

numberOfStrategies = numel(Strategy);

PeakGrid_kW = zeros(numberOfStrategies, 1);
GridImport_kWh = zeros(numberOfStrategies, 1);
GridExport_kWh = zeros(numberOfStrategies, 1);
NetGridEnergy_kWh = zeros(numberOfStrategies, 1);
GridExceedance_kWh = zeros(numberOfStrategies, 1);
RawEnergyCost_RMB = zeros(numberOfStrategies, 1);
BatteryThroughput_kWh = zeros(numberOfStrategies, 1);
MinimumSOC_pct = zeros(numberOfStrategies, 1);
MaximumSOC_pct = zeros(numberOfStrategies, 1);
FinalSOC_pct = zeros(numberOfStrategies, 1);
MaximumBatteryPower_kW = zeros(numberOfStrategies, 1);
MaximumPowerBalanceError_kW = zeros(numberOfStrategies, 1);
SOCIntegrationError_pct = zeros(numberOfStrategies, 1);
MeetsGridLimit = false(numberOfStrategies, 1);
SOCWithinLimits = false(numberOfStrategies, 1);
BatteryPowerWithinRating = false(numberOfStrategies, 1);

timeTrace = cell(numberOfStrategies, 1);
gridTrace = cell(numberOfStrategies, 1);
batteryTrace = cell(numberOfStrategies, 1);
socTrace = cell(numberOfStrategies, 1);
socTimeTrace = cell(numberOfStrategies, 1);
priceTrace = cell(numberOfStrategies, 1);

%% 6. Run both strategies with identical inputs

for strategyIndex = 1:numberOfStrategies

    assignin('base', ...
        'load_profile', ...
        timeseries(baseLoad, baseTime));

    assignin('base', ...
        'pv_profile', ...
        timeseries(basePV, baseTime));

    assignin('base', 'E_batt', E_batt_kWh);
    assignin('base', 'E_batt_kWh', E_batt_kWh);

    assignin('base', 'P_batt_max', P_batt_max_kW);
    assignin('base', 'P_batt_max_kW', P_batt_max_kW);

    assignin('base', 'P_grid_limit', P_grid_limit_kW);
    assignin('base', 'P_grid_limit_kW', P_grid_limit_kW);

    assignin('base', ...
        'SOC_initial', SOC_initial_value);

    assignin('base', ...
        'precharge_enable', precharge_enable_value);

    assignin('base', ...
        'price_profile', price_profile);

    assignin('base', ...
        'price_low_threshold_RMB_MWh', ...
        price_low_threshold_RMB_MWh);

    assignin('base', ...
        'price_aware_enable', ...
        PriceAwareEnable(strategyIndex));

    Simulink.sdi.clear;

    simOut = sim(modelName, ...
        'StopTime', '86400', ...
        'ReturnWorkspaceOutputs', 'on');

    P_grid_ts = simOut.get('P_grid_ems_sim');
    P_grid_base_ts = simOut.get('P_grid_base_sim');
    P_batt_ts = simOut.get('P_batt_sim');
    SOC_ts = simOut.get('SOC_sim');

    dayTime = P_grid_ts.Time(:);
    P_grid = P_grid_ts.Data(:);
    P_grid_base = P_grid_base_ts.Data(:);
    P_batt = P_batt_ts.Data(:);
    SOC = SOC_ts.Data(:);

    assert(numel(dayTime) >= 2, ...
        'Simulation output contains too few samples.');

    assert(all(diff(dayTime) > 0), ...
        'Simulation time must be strictly increasing.');

    assert(abs(dayTime(1)) <= 1e-9 ...
        && abs(dayTime(end) - 86400) <= 1e-9, ...
        'Simulation output must cover 0 to 86400 seconds.');

    currentPrice = interp1( ...
        price_profile.Time(:), ...
        price_profile.Data(:), ...
        dayTime, ...
        'previous', ...
        'extrap');

    % Treat each simulated value as applying over the interval that
    % follows it. The final endpoint has no subsequent interval.
    intervalHours = diff(dayTime) / 3600;

    assert(abs(sum(intervalHours) - 24) <= 1e-9, ...
        'The interval durations must sum to 24 hours.');

    gridInterval = P_grid(1:end-1);
    batteryInterval = P_batt(1:end-1);
    priceInterval = currentPrice(1:end-1);

    importPowerInterval = max(gridInterval, 0);
    exportPowerInterval = max(-gridInterval, 0);
    exceedancePowerInterval = max( ...
        gridInterval - P_grid_limit_kW, 0);

    PeakGrid_kW(strategyIndex) = max(P_grid);

    GridImport_kWh(strategyIndex) = sum( ...
        importPowerInterval .* intervalHours);

    GridExport_kWh(strategyIndex) = sum( ...
        exportPowerInterval .* intervalHours);

    NetGridEnergy_kWh(strategyIndex) = ...
        GridImport_kWh(strategyIndex) ...
        - GridExport_kWh(strategyIndex);

    GridExceedance_kWh(strategyIndex) = sum( ...
        exceedancePowerInterval .* intervalHours);

    RawEnergyCost_RMB(strategyIndex) = sum( ...
        importPowerInterval .* intervalHours ...
        .* priceInterval / 1000);

    BatteryThroughput_kWh(strategyIndex) = sum( ...
        abs(batteryInterval) .* intervalHours);

    % The MATLAB Function updates its persistent SOC during the sample
    % at t = 0. Therefore, SOC(1) represents the end of the first
    % 15-minute interval rather than the physical state at t = 0.
    % Reconstruct the correctly labelled state trace by prepending the
    % specified initial SOC and dropping the non-physical extra endpoint.
    SOC_state_time = [dayTime(1); dayTime(2:end)];
    SOC_state = [SOC_initial_value; SOC(1:end-1)];

    MinimumSOC_pct(strategyIndex) = ...
        100 * min(SOC_state);

    MaximumSOC_pct(strategyIndex) = ...
        100 * max(SOC_state);

    FinalSOC_pct(strategyIndex) = ...
        100 * SOC_state(end);

    chargedEnergyIntoCell_kWh = sum( ...
        max(-batteryInterval, 0) * 0.95 ...
        .* intervalHours);

    dischargedEnergyFromCell_kWh = sum( ...
        max(batteryInterval, 0) / 0.95 ...
        .* intervalHours);

    calculatedFinalSOC = SOC_initial_value ...
        + chargedEnergyIntoCell_kWh / E_batt_kWh ...
        - dischargedEnergyFromCell_kWh / E_batt_kWh;

    calculatedFinalSOC = min(max( ...
        calculatedFinalSOC, SOC_min), SOC_max);

    SOCIntegrationError_pct(strategyIndex) = ...
        100 * abs(calculatedFinalSOC - SOC_state(end));

    MaximumBatteryPower_kW(strategyIndex) = ...
        max(abs(P_batt));

    powerBalanceError = ...
        P_grid - (P_grid_base - P_batt);

    MaximumPowerBalanceError_kW(strategyIndex) = ...
        max(abs(powerBalanceError));

    MeetsGridLimit(strategyIndex) = ...
        PeakGrid_kW(strategyIndex) ...
        <= P_grid_limit_kW + 1e-6;

    SOCWithinLimits(strategyIndex) = ...
        min(SOC_state) >= SOC_min - 1e-9 ...
        && max(SOC_state) <= SOC_max + 1e-9;

    BatteryPowerWithinRating(strategyIndex) = ...
        max(abs(P_batt)) ...
        <= P_batt_max_kW + 1e-6;

    timeTrace{strategyIndex} = dayTime;
    gridTrace{strategyIndex} = P_grid;
    batteryTrace{strategyIndex} = P_batt;
    socTrace{strategyIndex} = SOC_state;
    socTimeTrace{strategyIndex} = SOC_state_time;
    priceTrace{strategyIndex} = currentPrice;
end

%% 7. Build the comparison table

PriceDate = repmat( ...
    priceData.priceDateList(priceDayIndex), ...
    numberOfStrategies, 1);

ComparisonTable = table( ...
    PriceDate, ...
    Strategy, ...
    PriceAwareEnable, ...
    PeakGrid_kW, ...
    GridImport_kWh, ...
    GridExport_kWh, ...
    NetGridEnergy_kWh, ...
    GridExceedance_kWh, ...
    RawEnergyCost_RMB, ...
    BatteryThroughput_kWh, ...
    MinimumSOC_pct, ...
    MaximumSOC_pct, ...
    FinalSOC_pct, ...
    MaximumBatteryPower_kW, ...
    MaximumPowerBalanceError_kW, ...
    SOCIntegrationError_pct, ...
    MeetsGridLimit, ...
    SOCWithinLimits, ...
    BatteryPowerWithinRating);

%% 8. Determine whether a direct cost claim is fair

terminalSOCDifference_pct = ...
    FinalSOC_pct(2) - FinalSOC_pct(1);

terminalSOCComparable = ...
    abs(terminalSOCDifference_pct) <= 0.5;

reliabilityComparable = ...
    all(MeetsGridLimit) ...
    && all(SOCWithinLimits) ...
    && all(BatteryPowerWithinRating) ...
    && all(MaximumPowerBalanceError_kW <= 1e-6) ...
    && all(SOCIntegrationError_pct <= 1e-6);

validDirectCostComparison = ...
    terminalSOCComparable ...
    && reliabilityComparable;

rawCostDifference_RMB = ...
    RawEnergyCost_RMB(2) ...
    - RawEnergyCost_RMB(1);

%% 9. Display results

fprintf('\n--- Single-day Price-aware EMS Comparison ---\n');
fprintf('Price date: %s\n', ...
    string(priceData.priceDateList(priceDayIndex), ...
    'yyyy-MM-dd'));
fprintf('Daily low-price threshold: %.2f RMB/MWh\n\n', ...
    price_low_threshold_RMB_MWh);

disp(ComparisonTable);

fprintf('\n--- Comparison Validity Check ---\n');
fprintf('Terminal SOC difference (price - fixed): %.3f percentage points\n', ...
    terminalSOCDifference_pct);
fprintf('Reliability comparable: %d\n', ...
    reliabilityComparable);
fprintf('Terminal SOC comparable within 0.5 point: %d\n', ...
    terminalSOCComparable);
fprintf('Valid direct cost comparison: %d\n', ...
    validDirectCostComparison);
fprintf('Raw cost difference (price - fixed): %.2f RMB\n', ...
    rawCostDifference_RMB);
fprintf('Maximum SOC-integration error: %.9f percentage points\n', ...
    max(SOCIntegrationError_pct));
fprintf(['Cost convention: grid-import energy only; ', ...
    'grid-export compensation is zero.\n']);

if validDirectCostComparison
    fprintf(['The raw energy-cost difference is directly comparable ', ...
        'for this test.\n']);
else
    fprintf(['Do not claim cost saving yet: reliability and/or ', ...
        'terminal stored energy is not comparable.\n']);
end

%% 10. Plot the comparison

figure( ...
    'Color', 'w', ...
    'Name', ...
    'Single-day Price-aware EMS Comparison');

tiledlayout(3, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

nexttile;

plot( ...
    socTimeTrace{1} / 3600, ...
    priceTrace{1}, ...
    'b-', ...
    'LineWidth', 1.8);

hold on;

yline( ...
    price_low_threshold_RMB_MWh, ...
    '--', ...
    'Low-price threshold', ...
    'Color', [0.1 0.6 0.2], ...
    'LineWidth', 1.3);

grid on;
xlim([0 24]);
ylabel('RMB/MWh');
title('Shandong Day-ahead Economic Clearing Price');

nexttile;

plot( ...
    timeTrace{1} / 3600, ...
    gridTrace{1}, ...
    'b--', ...
    'LineWidth', 1.8);

hold on;

plot( ...
    socTimeTrace{2} / 3600, ...
    gridTrace{2}, ...
    'Color', [0.9 0.4 0.05], ...
    'LineWidth', 1.8);

yline( ...
    P_grid_limit_kW, ...
    'r--', ...
    '100 kW grid limit', ...
    'LineWidth', 1.3);

grid on;
xlim([0 24]);
ylabel('Grid power (kW)');
title('Grid Import');
legend(Strategy, 'Location', 'best');

nexttile;

plot( ...
    timeTrace{1} / 3600, ...
    100 * socTrace{1}, ...
    'b--', ...
    'LineWidth', 1.8);

hold on;

plot( ...
    timeTrace{2} / 3600, ...
    100 * socTrace{2}, ...
    'Color', [0.9 0.4 0.05], ...
    'LineWidth', 1.8);

yline(20, 'r--', '20% lower limit');
yline(90, 'r--', '90% upper limit');
yline(25, 'k--', '25% design target');

grid on;
xlim([0 24]);
ylim([15 95]);
xlabel('Time of day (h)');
ylabel('SOC (%)');
title('Battery SOC');
legend(Strategy, 'Location', 'best');

selectedPriceDateText = char(string( ...
    priceData.priceDateList(priceDayIndex), ...
    'yyyy-MM-dd'));

sgtitle(sprintf( ...
    'Representative Sunny/Normal Day under %s Price Signal', ...
    selectedPriceDateText));
%% 11. Save outputs

csvFile = fullfile( ...
    resultsDir, ...
    'price_aware_single_day_comparison.csv');

matFile = fullfile( ...
    resultsDir, ...
    'price_aware_single_day_comparison.mat');

figureFile = fullfile( ...
    resultsDir, ...
    'price_aware_single_day_comparison.png');

writetable(ComparisonTable, csvFile);

save(matFile, ...
    'ComparisonTable', ...
    'priceDayIndex', ...
    'price_low_threshold_RMB_MWh', ...
    'terminalSOCDifference_pct', ...
    'terminalSOCComparable', ...
    'reliabilityComparable', ...
    'validDirectCostComparison', ...
    'rawCostDifference_RMB', ...
    'timeTrace', ...
    'gridTrace', ...
    'batteryTrace', ...
    'socTrace', ...
    'socTimeTrace', ...
    'priceTrace');

exportgraphics(gcf, figureFile, ...
    'Resolution', 200);

fprintf('\nResults saved to:\n%s\n', resultsDir);
